class Macsweep < Formula
  desc "Clean up and look after your Mac from a simple terminal menu"
  homepage "https://github.com/shannong57/macsweep"
  url "https://github.com/shannong57/macsweep/archive/refs/tags/v0.8.4.tar.gz"
  sha256 "ece33ffbaee22c92b92e2b1076bc7b300848ddb8538ffb4e5a3aab8630f705c7"
  license "MIT"

  depends_on :macos

  def install
